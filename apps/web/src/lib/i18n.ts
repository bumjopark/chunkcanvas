export type Lang = 'en' | 'ko';
export type StringKey = keyof Strings;

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('chunkcanvas.lang');
    if (saved === 'en' || saved === 'ko') return saved;
  } catch {
    /* ignore */
  }
  return 'en';
}

export const useLang = create<{ lang: Lang; toggle: () => void }>((set, get) => ({
  lang: initialLang(),
  toggle: () => {
    const lang = get().lang === 'en' ? 'ko' : 'en';
    try {
      localStorage.setItem('chunkcanvas.lang', lang);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = lang;
    set({ lang });
  },
}));

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  const table = lang === 'ko' ? ko : en;
  return table[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

export function useT() {
  const lang = useLang((s) => s.lang);
  return (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function formatDuration(lang: Lang, seconds: number): string {
  const h = seconds / 3600;
  if (h >= 1 && Number.isInteger(h)) return lang === 'ko' ? `${h}시간` : `${h} hour${h === 1 ? '' : 's'}`;
  const m = Math.round(seconds / 60);
  return lang === 'ko' ? `${m}분` : `${m} minutes`;
}
